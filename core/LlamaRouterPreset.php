<?php
declare(strict_types=1);

namespace mara\core;

use mara\database\mModels;
use RuntimeException;

final class LlamaRouterPreset
{
    private const RUNTIME_KEYS = [
        'gpu_layers'    => 'n-gpu-layers',
        'batch_size'    => 'batch-size',
        'ubatch_size'   => 'ubatch-size',
        'threads'       => 'threads',
        'threads_batch' => 'threads-batch',
        'flash_attn'    => 'flash-attn',
        'cache_type_k'  => 'cache-type-k',
        'cache_type_v'  => 'cache-type-v',
        'n_cpu_moe'     => 'n-cpu-moe',
        'n_cpu_ffn'     => 'n-cpu-ffn',
    ];

    public static function modelName(int $id): string
    {
        if ($id <= 0) {
            throw new RuntimeException('Invalid Mara model ID.');
        }

        return 'mara-' . $id;
    }

    /**
     * Generate the router preset from all llama.cpp Mara models.
     *
     * The caller must be trusted: this method deliberately reads
     * models belonging to every user.
     */
    public function generate(string $destination, string $modelDir): int
    {
        $repository = new mModels();
        $models = $repository->getAll(0, true, 'llamacpp');

        $lines = [
            '# Generated by Mara-Lab. Do not edit manually.',
            '# Mara character presets for llama.cpp Router.',
            '',
        ];

        $count = 0;

        foreach ($models as $model) {
            $id = (int)($model['id'] ?? 0);
            $baseModel = trim((string)($model['basemodel'] ?? ''));

            if ($id <= 0 || $baseModel === '') {
                continue;
            }

            $parameters = $model['parameters'] ?? [];

            if (is_string($parameters)) {
                $parameters = json_decode($parameters, true);
            }

            if (!is_array($parameters)) {
                $parameters = [];
            }

            $runtime = $parameters['runtime'] ?? [];
            if (!is_array($runtime)) {
                $runtime = [];
            }

            $modelPath = realpath(
                rtrim($modelDir, '/') . '/' . basename($baseModel)
            );

            if ($modelPath === false || !is_file($modelPath)) {
                throw new RuntimeException(
                    'GGUF file not found for Mara model ' . $id
                );
            }

            $lines[] = '[' . self::modelName($id) . ']';
            $lines[] = 'model = ' . $this->safeValue($modelPath);

            $mmproj = trim((string)($model['mmproj'] ?? ''));
            if ($mmproj !== '') {
                $mmprojPath = realpath(
                    rtrim($modelDir, '/') . '/' . basename($mmproj)
                );

                if ($mmprojPath === false || !is_file($mmprojPath)) {
                    throw new RuntimeException(
                        'MMProj file not found for Mara model ' . $id
                    );
                }

                $lines[] = 'mmproj = ' . $this->safeValue($mmprojPath);
            }

            $ctx = $parameters['num_ctx'] ?? null;
            if (is_numeric($ctx) && (int)$ctx >= 512) {
                $lines[] = 'ctx-size = ' . (int)$ctx;
            }

            foreach (self::RUNTIME_KEYS as $key => $option) {
                if (!array_key_exists($key, $runtime)) {
                    continue;
                }

                $value = $runtime[$key];

                if (!is_scalar($value) || is_bool($value)) {
                    continue;
                }

                $value = trim((string)$value);
                if ($value === '') {
                    continue;
                }

                $lines[] = $option . ' = ' . $this->safeValue($value);
            }

            if (array_key_exists('cpu_moe', $runtime)) {
                $lines[] = 'cpu-moe = '
                    . (!empty($runtime['cpu_moe']) ? '1' : '0');
            }

            $lines[] = '';
            $count++;
        }

        $contents = implode("\n", $lines) . "\n";
        $directory = dirname($destination);

        if (!is_dir($directory) || !is_writable($directory)) {
            throw new RuntimeException(
                'Router preset directory is not writable: ' . $directory
            );
        }

        $temporary = tempnam($directory, '.llama-router-');

        if ($temporary === false) {
            throw new RuntimeException('Cannot create temporary preset.');
        }

        try {
            if (file_put_contents($temporary, $contents, LOCK_EX)
                !== strlen($contents)) {
                throw new RuntimeException('Cannot write router preset.');
            }

            if (!chmod($temporary, 0640)) {
                throw new RuntimeException('Cannot set preset permissions.');
            }

            if (!rename($temporary, $destination)) {
                throw new RuntimeException('Cannot replace router preset.');
            }
        } finally {
            if (is_file($temporary)) {
                unlink($temporary);
            }
        }

        return $count;
    }

    private function safeValue(string $value): string
    {
        if (preg_match('/[\r\n\[\]#;]/', $value)) {
            throw new RuntimeException(
                'Unsupported character in router preset value.'
            );
        }

        return $value;
    }
}
